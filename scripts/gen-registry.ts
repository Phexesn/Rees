/**
 * Scans src/modules/<id>/ folders and writes the module registries.
 * Run automatically by `npm run dev` / `npm run build`; run manually with
 * `npm run gen:registry` after adding a module folder.
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.join(process.cwd(), "src", "modules");
const outDir = path.join(root, "_generated");

const ids = readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_"))
  .map((d) => d.name)
  .filter((id) => existsSync(path.join(root, id, "module.ts")))
  .sort();

for (const id of ids) {
  if (!existsSync(path.join(root, id, "View.tsx"))) {
    throw new Error(`Module "${id}" is missing View.tsx`);
  }
}

const ident = (id: string) => id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const header = "// AUTO-GENERATED by scripts/gen-registry.ts — do not edit by hand.\n";

const registry = `${header}import "server-only";
import type { ContentModule } from "@/modules/types";
${ids.map((id) => `import ${ident(id)} from "@/modules/${id}/module";`).join("\n")}

export const MODULES: Record<string, ContentModule> = {
${ids.map((id) => `  "${id}": ${ident(id)} as unknown as ContentModule,`).join("\n")}
};
`;

const views = `${header}"use client";
import type { ComponentType } from "react";
import type { ModuleViewProps } from "@/modules/view-types";
${ids.map((id) => `import ${ident(id)}View from "@/modules/${id}/View";`).join("\n")}

export const VIEWS: Record<string, ComponentType<ModuleViewProps>> = {
${ids.map((id) => `  "${id}": ${ident(id)}View as ComponentType<ModuleViewProps>,`).join("\n")}
};
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(path.join(outDir, "registry.ts"), registry);
writeFileSync(path.join(outDir, "views.ts"), views);
console.log(`Module registry: ${ids.length} modules (${ids.join(", ")})`);
